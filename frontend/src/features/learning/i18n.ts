const STRINGS: Record<Lang, Record<Key, string>> = { en, sl };

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s = STRINGS[lang][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function useT() {
  const { language } = useAuth();
  const forced = useContext(LangContext);
  const lang: Lang = forced ?? language;
  const t = useCallback((key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars), [lang]);
  return { lang, t };
}

export function gradeText(t: (key: Key, vars?: Record<string, string | number>) => string, grade: number | null | undefined): string {
  if (!grade) return "";
  return grade <= 9 ? t("gradePrimary", { n: grade }) : t("gradeSecondary", { n: grade - 9 });
}

export function formatDay(iso: string, lang: Lang = "en"): string {
  return new Date(`${iso.slice(0, 10)}T12:00:00`).toLocaleDateString(lang === "sl" ? "sl-SI" : "en-GB", {
    weekday: "short",
    day: "numeric",
    month: "short",
  });
}
